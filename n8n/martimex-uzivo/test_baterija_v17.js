function ocijeni(e, r) {
  const puts = r.urls.map(put); const bezQ = puts.map(p => p.split('?')[0]);
  switch (e.t) {
    case 'pg': return r.akcija === 'dohvati' && bezQ.some(p => e.p.includes(p));
    case 'ls': return r.akcija === 'dohvati' && !!puts[0] && bezQ[0].startsWith(e.pref) && (!e.q || puts[0].includes(e.q));
    case 'pr': return r.akcija === 'dohvati' && puts.some(p => e.re.some(re => re.test(p)));
    case 'nf': return r.tip === 'nije_pronadjeno';
    case 'err': return r.akcija === 'odgovori' && r.ok === false;
    case 'any': return e.e.some(x => ocijeni(x, r));
  }
}
